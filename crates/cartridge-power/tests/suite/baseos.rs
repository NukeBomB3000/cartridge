use cartridge_power::{parse_baseos_release, read_baseos_release, BaseosRelease};

const RG35XXSP: &str = "# Generated by build-rootfs.sh; do not edit in the image.
BASEOS=1
BASEOS_PLATFORM=h700
BASEOS_VERSION=1.3.0
BASEOS_BUILD=v1.3.0-0-gabc1234
BASEOS_TARGET=rg35xxsp
BASEOS_DEVICE=rg35xx
BASEOS_MODEL=\"RG35XX SP\"
BASEOS_MODEL_STRING=RG35xxSP
BASEOS_PANEL_ROTATION_CCW=0
BASEOS_WIFI=1
BASEOS_BLUETOOTH=1
";

#[test]
fn the_release_file_names_the_handheld() {
    assert_eq!(
        parse_baseos_release(RG35XXSP),
        BaseosRelease {
            target: Some("rg35xxsp".into()),
            model: Some("RG35XX SP".into()),
            version: Some("1.3.0".into()),
            rotation_ccw: 0,
            wifi: Some(true),
            bluetooth: Some(true),
        }
    );
}

#[test]
fn a_turned_panel_and_a_model_without_radios_are_read() {
    let r = parse_baseos_release(
        "BASEOS_TARGET=rg28xx\nBASEOS_PANEL_ROTATION_CCW=90\nBASEOS_WIFI=false\nBASEOS_BLUETOOTH=False\n",
    );
    assert_eq!(r.target.as_deref(), Some("rg28xx"));
    assert_eq!(r.rotation_ccw, 90);
    assert_eq!((r.wifi, r.bluetooth), (Some(false), Some(false)));
}

#[test]
fn anything_unreadable_is_left_unknown_rather_than_guessed() {
    let r = parse_baseos_release(
        "junk\nBASEOS_PANEL_ROTATION_CCW=sideways\nBASEOS_WIFI=maybe\nBASEOS_TARGET=\n",
    );
    assert_eq!(r, BaseosRelease::default());
    assert_eq!(
        parse_baseos_release("BASEOS_PANEL_ROTATION_CCW=450").rotation_ccw,
        90
    );
}

#[test]
fn a_system_that_is_not_baseos_has_no_release() {
    let d = tempfile::tempdir().unwrap();
    assert_eq!(read_baseos_release(&d.path().join("baseos-release")), None);
    std::fs::write(d.path().join("baseos-release"), RG35XXSP).unwrap();
    assert_eq!(
        read_baseos_release(&d.path().join("baseos-release"))
            .and_then(|r| r.target)
            .as_deref(),
        Some("rg35xxsp")
    );
}
